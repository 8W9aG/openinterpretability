"""Neuronpedia's explanations through the adversarial review.

The command is `open-interpretability neuronpedia-review`.

The score baseline (:mod:`openinterp.neuronpedia_baseline`) asks how well an explanation
predicts held-out text. This asks whether it survives a reviewer who writes probes to
break it. Each latent that Neuronpedia explains gets a copy of its newest submission.
The copy has Neuronpedia's explanation as the hypothesis. It claims no activating tokens
and a retrospective mechanism, because Neuronpedia's text claims nothing else. A reviewer
then writes probes from that copy alone, and the harness measures them.

Neuronpedia makes no counterfactual predictions. So the comparison uses the gates that
the probes decide (``PROBE_GATES``), for both explanations. The records stay out of the
registry: they never change a unit's standing.
"""

from __future__ import annotations

from collections.abc import Sequence
from statistics import mean

from pydantic import BaseModel

from openinterp.baseline import sign_test

# Gates that the proposer's own claims decide, not the probes: its predicted edits
# (counterfactual_reproduction) and its claimed mechanism (lookahead_consistent).
# independent_review is about who proposed. Neuronpedia claims none of these.
NOT_PROBE_GATES = frozenset(
    {"counterfactual_reproduction", "lookahead_consistent", "independent_review"}
)
METRICS = ("balanced_accuracy", "specificity", "sensitivity")


def probe_gates(gates: dict[str, bool]) -> dict[str, bool]:
    """The gates of ``gates`` that the probes decide."""
    return {k: v for k, v in gates.items() if k not in NOT_PROBE_GATES}


class ReviewRow(BaseModel):
    """One latent: the agent's newest review against the review of Neuronpedia's text."""

    slug: str
    experiment_id: str  # the agent's experiment, whose submission was copied
    url: str | None
    agent_status: str
    agent_explanation: str
    neuronpedia_explanation: str
    explainer: str
    reviewer_model: str | None = None  # None while the probes are missing
    agent: dict
    neuronpedia: dict | None = None


def side(metrics) -> dict:
    """The probe metrics and probe gates of one verdict's ``metrics``."""
    gates = probe_gates(metrics.gates)
    return {
        **{name: getattr(metrics, name) for name in METRICS},
        "gates": gates,
        "probe_verified": all(gates.values()),
    }


def report(rows: Sequence[ReviewRow]) -> str:
    """Return the comparison as a Markdown page."""
    done = [r for r in rows if r.neuronpedia is not None]
    agent_ok = sum(r.agent["probe_verified"] for r in done)
    np_ok = sum(r.neuronpedia["probe_verified"] for r in done)
    lines = [
        "# Neuronpedia explanations through the adversarial review",
        "",
        "Generated by `open-interpretability neuronpedia-review`. Do not edit. Method: "
        "`openinterp/neuronpedia_review.py` and docs/PROTOCOL.md §4.",
        "",
        f"Explanations from [Neuronpedia](https://www.neuronpedia.org), credited to the model "
        f"that wrote them. Each latent's newest submission was copied with Neuronpedia's "
        f"explanation as the hypothesis and no claimed tokens. A reviewer wrote probes "
        f"for that copy alone. Neuronpedia makes no counterfactual predictions, so both "
        f"sides are judged on the gates that the probes decide: every gate except "
        f"{', '.join(sorted(NOT_PROBE_GATES))}. These reviews are not registry records. "
        f"Reviewed: {len(done)} of {len(rows)} latents.",
        "",
        "Two things favour the agent. Its side is the unit's newest experiment, which is "
        "often a revision written after earlier reviews. And its probes came from that "
        "experiment's own reviewer, which can be another model than the one here.",
        "",
        "| | Agent | Neuronpedia |",
        "| --- | --- | --- |",
        f"| Passes every probe gate | {agent_ok} of {len(done)} | {np_ok} of {len(done)} |",
    ]
    lines += [line for name in METRICS if (line := _metric_line(done, name))]
    failed = _failed_gates(done)
    if failed:
        lines += ["", "Probe gates that Neuronpedia's explanations failed: " + failed + "."]
    return "\n".join(lines + ["", *_unit_lines(rows)]) + "\n"


def _metric_line(done: Sequence[ReviewRow], name: str) -> str | None:
    """One table row: the mean of metric ``name`` on each side, with a sign test."""
    pairs = [(r.agent[name], r.neuronpedia[name]) for r in done]
    pairs = [(a, b) for a, b in pairs if a is not None and b is not None]
    if not pairs:
        return None
    p = sign_test([b - a for a, b in pairs])
    return (
        f"| {name.replace('_', ' ').capitalize()} (mean, n = {len(pairs)}) | "
        f"{mean(a for a, _ in pairs):.2f} | {mean(b for _, b in pairs):.2f}"
        f"{'' if p is None else f' (sign test p = {p:.2g})'} |"
    )


def _unit_lines(rows: Sequence[ReviewRow]) -> list[str]:
    """The per-latent table: each side's verdict on the probe gates, and balanced accuracy."""
    lines = [
        "| Unit | Agent | Neuronpedia's explanation | Neuronpedia | Balanced accuracy |",
        "| --- | --- | --- | --- | --- |",
    ]
    for r in sorted(rows, key=lambda r: r.slug):
        unit = f"[{r.slug}]({r.url})" if r.url else r.slug
        theirs = "not reviewed yet" if r.neuronpedia is None else _verdict(r.neuronpedia)
        acc = "—"
        if r.neuronpedia is not None:
            acc = f"{r.agent['balanced_accuracy']:.2f} → {r.neuronpedia['balanced_accuracy']:.2f}"
        lines.append(
            f"| {unit} | {_verdict(r.agent)} | {_cell(r.neuronpedia_explanation)} | "
            f"{theirs} | {acc} |"
        )
    return lines


def _verdict(s: dict) -> str:
    return (
        "passes"
        if s["probe_verified"]
        else "fails " + ", ".join(sorted(k for k, ok in s["gates"].items() if not ok))
    )


def _failed_gates(done: Sequence[ReviewRow]) -> str:
    from collections import Counter

    counts = Counter(k for r in done for k, ok in r.neuronpedia["gates"].items() if not ok)
    return ", ".join(f"{k} ×{n}" for k, n in counts.most_common())


def _cell(text: str) -> str:
    return " ".join(text.split()).replace("|", "\\|").replace("<", "&lt;")
