# WikiText's top-level heading row (" = Title = \n") starts an article; sections are
# " = = Section = = \n". Its text is tokenised: "1 @,@ 000", "well @-@ known", "lobster ,".
_WIKITEXT_TITLE = re.compile(r" = [^=].* = \n?")
_WIKITEXT_HEADING = re.compile(r"(?:= )+(.*?)(?: =)+")
_WIKITEXT_DETOKENIZE = [
    (re.compile(r" @(.)@ "), r"\1"),  # number separators and hyphens
    (re.compile(r" ([.,;:!?%)\]}])"), r"\1"),
    (re.compile(r"([(\[{$]) "), r"\1"),
    (re.compile(r" (n't|'s|'re|'ve|'m|'ll|'d)\b"), r"\1"),
    (re.compile(r" ' s\b"), "'s"),  # possessive after punctuation: "Inc. ' s"
    (re.compile(r"s ' "), "s' "),  # plural possessive
    (re.compile(r'" ([^"]*?) "'), r'"\1"'),
]


def wikitext_articles(rows: Sequence[str | None]) -> list[str]:
    """The WikiText articles that start and end within ``rows``, detokenised, with
    headings as plain lines and paragraphs separated by blank lines. An article cut by
    the start or end of ``rows`` (a row group's edge) is dropped, not truncated."""
    starts = [i for i, row in enumerate(rows) if _WIKITEXT_TITLE.fullmatch(row or "")]
    return [_wikitext_article(rows[a:b]) for a, b in pairwise(starts)]


def _wikitext_article(rows: Sequence[str | None]) -> str:
    paragraphs = []
    for row in rows:
        text = (row or "").strip()
        if heading := _WIKITEXT_HEADING.fullmatch(text):
            text = heading.group(1)
        for pattern, repl in _WIKITEXT_DETOKENIZE:
            text = pattern.sub(repl, text)
        if text:
            paragraphs.append(text)
    return "\n\n".join(paragraphs)


# Row layouts other than one document per row: rows of one row group -> its documents.
LAYOUTS = {"wikitext": wikitext_articles}

# Document fields a corpus may carry besides "text", and the label set each gives the scan
# (`harness/annotations.py`). Exact labels from the dataset, never detected.
DOCUMENT_LABELS = {"lang": LANGUAGE}


def source_path(corpus_path: Path) -> Path:
    """``corpus.jsonl`` -> ``corpus.source.json``."""
    return corpus_path.with_name(corpus_path.name.split(".")[0] + ".source.json")


def sample_documents(
    fs,
    paths: list[str],
    *,
    text_column: str,
    documents: int,
    seed: int,
    max_chars: int,
    docs_per_row_group: int,
    layout: str | None = None,
) -> list[str]:
    """Up to ``documents`` non-empty texts, cut to ``max_chars``, from Parquet files on ``fs``.
    With a ``layout``, each row group's rows are first joined into its documents."""
    rng = random.Random(seed)
    paths = sorted(paths)
    # One footer read per file: in parallel, since a dataset of 880 files takes minutes serially.
    with ThreadPoolExecutor(16) as pool:
        counts = list(pool.map(lambda path: _row_groups(fs, path), paths))
    groups = [(path, i) for path, n in zip(paths, counts, strict=True) for i in range(n)]
    rng.shuffle(groups)
    # Few row groups (a small dataset): take more from each, so the sample still fills.
    take = max(docs_per_row_group, math.ceil(documents / max(len(groups), 1)))
    out: list[str] = []
    for texts in _read_groups(fs, groups, text_column):
        if layout is not None:
            texts = LAYOUTS[layout](texts)
        order = rng.sample(range(len(texts)), len(texts))
        picked = [j for j in order if (texts[j] or "").strip()][:take]  # empties don't count
        for j in sorted(picked):
            out.append(texts[j].strip()[:max_chars])
            if len(out) >= documents:
                return out
    return out


def first_documents(
    fs,
    paths: list[str],
    *,
    text_column: str,
    documents: int,
    max_chars: int,
    layout: str | None = None,
) -> list[str]:
    """The first ``documents`` non-empty texts of the Parquet files on ``fs``, in sorted
    file order, cut to ``max_chars`` but not stripped (as the registry's corpus was)."""
    out: list[str] = []
    for path in sorted(paths):
        groups = [(path, i) for i in range(_row_groups(fs, path))]
        for texts in _read_groups(fs, groups, text_column):
            if layout is not None:
                texts = LAYOUTS[layout](texts)
            for text in texts:
                if (text or "").strip():
                    out.append(text[:max_chars])
                    if len(out) >= documents:
                        return out
    return out


def _row_groups(fs, path: str) -> int:
    with fs.open(path, "rb") as fh:
        return pq.ParquetFile(fh).num_row_groups


def _read_groups(fs, groups, column: str) -> Iterator[list]:
    for path, i in groups:
        with fs.open(path, "rb") as fh:
            yield pq.ParquetFile(fh).read_row_group(i, columns=[column]).column(column).to_pylist()


def jsonl_bytes(
    texts: Sequence[str], ascii: bool = False, labels: dict[str, Sequence[str]] | None = None
) -> bytes:
    """``texts`` as a JSONL corpus: one ``{"text": ...}`` per line, with each of ``labels``
    (a field of :data:`DOCUMENT_LABELS` -> one value per document) after it, and non-ASCII
    characters \\u-escaped if ``ascii``."""
    labels = labels or {}
    rows = ({"text": t} | {k: v[i] for k, v in labels.items()} for i, t in enumerate(texts))
    return "".join(json.dumps(row, ensure_ascii=ascii) + "\n" for row in rows).encode()


def sample_tokens(
    tokenizer, texts: Sequence[str], max_tokens: int, seed: int
) -> tuple[list[str], CorpusSample]:
    """A seeded sample of whole documents with at most ``max_tokens`` tokens (see
    :class:`CorpusSample`), in corpus order, and its description."""
    picked, sample = sample_indices(tokenizer, texts, max_tokens, seed)
    return [texts[i] for i in picked], sample


def sample_indices(
    tokenizer, texts: Sequence[str], max_tokens: int, seed: int
) -> tuple[list[int], CorpusSample]:
    """:func:`sample_tokens`, as the sampled documents' indices in corpus order."""
    if not texts:
        raise ValueError("the corpus has no documents to sample")
    order = random.Random(seed).sample(range(len(texts)), len(texts))
    picked: list[int] = []
    total = 0
    for i in order:
        n = len(tokenizer.encode(texts[i], add_special_tokens=False))
        if picked and total + n > max_tokens:
            continue  # a shorter document later in the order may still fit
        picked.append(i)
        total += n
    picked.sort()
    sample = [texts[i] for i in picked]
    return picked, CorpusSample(
        seed=seed,
        max_tokens=max_tokens,
        documents=len(sample),
        corpus_documents=len(texts),
        tokens=total,
        sha256=hashlib.sha256(jsonl_bytes(sample)).hexdigest(),
    )


def write_corpus(
    texts: list[str], out: Path, *, ascii: bool = False, labels=None, **source
) -> CorpusSource:
    """Write the JSONL corpus (with each document's ``labels``) and its source sidecar;
    returns the source."""
    out.parent.mkdir(parents=True, exist_ok=True)
    data = jsonl_bytes(texts, ascii, labels)
    out.write_bytes(data)
    record = CorpusSource(
        documents=len(texts), sha256=hashlib.sha256(data).hexdigest(), ascii=ascii, **source
    )
    source_path(out).write_text(record.model_dump_json(indent=2) + "\n", encoding="utf-8")
    return record


def load_source(corpus_path: Path, sha256: str) -> CorpusSource | None:
    """The corpus's source sidecar, if it exists and describes these exact bytes."""
    path = source_path(corpus_path)
    if not path.exists():
        return None
    source = CorpusSource.model_validate_json(path.read_text(encoding="utf-8"))
    return source if source.sha256 == sha256 else None


def load_sources(paths: Sequence[Path]) -> dict[str, CorpusSource]:
    """Committed source sidecars by the SHA-256 they describe; missing paths are skipped.

    The build uses them to show the source of records that scanned a corpus before its
    sidecar existed, matched by ``provenance.corpus_sha256``, as inferred, not recorded.
    """
    sources = {}
    for path in paths:
        if Path(path).exists():
            source = CorpusSource.model_validate_json(Path(path).read_text(encoding="utf-8"))
            sources[source.sha256] = source
    return sources


def build_from_hub(
    dataset: str,
    out: Path,
    *,
    files: str,
    text_column: str = "text",
    revision: str | None = None,
    documents: int = 500,
    seed: int = 0,
    max_chars: int = 3000,
    docs_per_row_group: int = 20,
    layout: str | None = None,
    first: bool = False,
    ascii: bool = False,
    lang_pattern: str | None = None,
    detect_lang: bool = False,
) -> CorpusSource:
    """Sample a corpus from a Hugging Face dataset at a pinned revision, or with ``first``
    take its first documents. With ``lang_pattern`` (see :class:`Preset`), each document
    records its glob's language as ``lang``; with ``detect_lang``, the language
    :mod:`openinterp.langid` detects, where it is sure of one."""
    if lang_pattern and detect_lang:
        raise ValueError("a corpus's languages come from lang_pattern or detect_lang, not both")
    from huggingface_hub import HfApi, HfFileSystem

    api = HfApi()
    info = api.dataset_info(dataset, revision=revision)
    license_ = _license(api, dataset, info, revision)
    fs = HfFileSystem()
    read = {"text_column": text_column, "max_chars": max_chars, "layout": layout}
    take = (
        partial(first_documents, fs, **read)
        if first
        else partial(sample_documents, fs, seed=seed, docs_per_row_group=docs_per_row_group, **read)
    )
    texts, langs = _read_globs(fs, f"{dataset}@{info.sha}", files, documents, take)
    langs = [_glob_lang(lang_pattern, glob) for glob in langs]
    detector = None
    if detect_lang:
        from openinterp import langid

        langs, detector = langid.detect(texts), langid.DETECTOR
    return write_corpus(
        texts,
        out,
        labels={"lang": langs} if lang_pattern or detect_lang else None,
        dataset=dataset,
        revision=info.sha,
        files=files,
        text_column=text_column,
        seed=seed,
        max_chars=max_chars,
        docs_per_row_group=docs_per_row_group,
        layout=layout,
        first=first,
        ascii=ascii,
        lang_pattern=lang_pattern,
        lang_detector=detector,
        license=", ".join(license_) if isinstance(license_, list) else license_,
    )


def _read_globs(fs, repo: str, files: str, documents: int, take):
    """The documents ``take(paths, documents=n)`` reads from ``files``' globs, and the glob
    each came from. Several globs (e.g. one per language) give an equal share each, the
    first taking extras."""
    texts, origins = [], []
    globs = files.split(",")
    for i, glob in enumerate(globs):
        paths = fs.glob(f"datasets/{repo}/{glob}")
        if not paths:
            raise FileNotFoundError(f"no files match {glob!r} in {repo}")
        share = documents // len(globs) + (i < documents % len(globs))
        texts += take(paths, documents=share)
        origins += [glob] * (len(texts) - len(origins))
    return texts, origins


def _glob_lang(pattern: str | None, glob: str) -> str | None:
    match = re.search(pattern, glob) if pattern else None
    if pattern and match is None:
        raise ValueError(f"{glob!r} names no language under the pattern {pattern!r}")
    return match.group(1) if match else None


def _license(api, dataset: str, info, revision: str | None):
    """The dataset card's licence (a string or a list), or ``None``."""
    if info.card_data is None and revision is not None:
        # Branches like refs/convert/parquet carry no dataset card: use the default branch's.
        card_data = api.dataset_info(dataset).card_data
    else:
        card_data = info.card_data
    return card_data.to_dict().get("license") if card_data else None
