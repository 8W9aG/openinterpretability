# What `openinterp audit` scans by default (protocol 0.7): a fixed seed, so every audit
# of a corpus reads the same documents and their scales are comparable.
DEFAULT_SAMPLE_TOKENS = 200_000
DEFAULT_SAMPLE_SEED = 0


@dataclass(frozen=True)
class Preset:
    dataset: str
    files: str  # glob within the dataset repo; comma-separated globs are sampled equally
    text_column: str = "text"
    revision: str | None = None  # default branch or tag; pinned to a commit on use
    layout: str | None = None  # how rows become documents (see LAYOUTS); None: one per row
    docs_per_row_group: int = 20
    # A regular expression whose group, matched in each file glob, is its documents' `lang`.
    lang_pattern: str | None = None


