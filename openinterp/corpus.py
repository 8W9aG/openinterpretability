# What `openinterp audit` scans by default (protocol 0.7). The seed is fixed, so every
# audit of a corpus reads the same documents, and their scales are comparable.
DEFAULT_SAMPLE_TOKENS = 200_000
DEFAULT_SAMPLE_SEED = 0


@dataclass(frozen=True)
class Preset:
    """A dataset that ``openinterp corpus --dataset`` can sample, and how to read it."""

    dataset: str
    files: str  # glob within the dataset repo; comma-separated globs are sampled equally
    text_column: str = "text"  # comma-separated columns join into one document
    revision: str | None = None  # default branch or tag; pinned to a commit on use
    layout: str | None = None  # how rows become documents (see LAYOUTS); None: one per row
    docs_per_row_group: int = 20
    # A regular expression whose group, matched in each file glob, is its documents' `lang`.
    lang_pattern: str | None = None
    # The dataset column that gives each document's programming language (`code_language`).
    code_language_column: str | None = None


